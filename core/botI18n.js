let cachedLang = 'en';

// Einmalig beim Adapter-Start aufrufen (z. B. in onReady), bevor irgendein
// Bot-Text gebraucht wird. Fällt bei jedem Fehler still auf Englisch zurück.
async function initBotI18n(adapter) {
    try {
        const systemConfig = await adapter.getForeignObjectAsync('system.config');
        const lang = systemConfig?.common?.language;
        if (lang && SUPPORTED_LANGS.includes(lang)) {
            cachedLang = lang;
        }
    } catch {
        // Fallback bleibt 'en'
    }
}

function t(key, vars) {
    const entry = TRANSLATIONS[key];
    let str = (entry && (entry[cachedLang] || entry.en)) || key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            str = str.split(`{${k}}`).join(v);
        }
    }
    return str;
}

module.exports = { initBotI18n, t, SUPPORTED_LANGS };
